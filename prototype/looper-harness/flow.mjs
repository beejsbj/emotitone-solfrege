import { chromium } from 'playwright';
const b = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required'] });
const p = await b.newPage({ viewport: { width: 390, height: 844 }, hasTouch: true });
const errs = []; p.on('pageerror', e => errs.push(String(e))); p.on('console', m => m.type()==='error' && errs.push(m.text()));
await p.goto('http://localhost:5175/');
await p.waitForTimeout(3500);
await p.getByRole('button', { name: /Play EmotiTone/ }).click();
await p.waitForTimeout(3000);
const state = () => p.evaluate(() => { const s = document.querySelector('#app').__vue_app__.config.globalProperties.$pinia._s; const l = s.get('loopPrototype'); const ph = s.get('phrases');
  return { bars: l.bars, bpm: l.bpm, running: l.running, armed: l.armed, phase: +l.phase().toFixed(3), layers: l.layers.map(x => ({ n: x.notes.length, len: x.lengthMs, inst: x.instrument, starts: x.notes.map(n => Math.round(n.pressTime)) })), take: ph.takeNotes.length, recent: ph.shelves.recent.length, kept: ph.shelves.kept.length }; });
const play = async (keys, gap = 450) => { for (const k of keys) { await p.keyboard.down(k); await p.waitForTimeout(200); await p.keyboard.up(k); await p.waitForTimeout(gap - 200); } };
await p.screenshot({ path: 'b-app.png' });
