import { chromium } from 'playwright';
const b = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required'] });
const p = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
const errs = []; p.on('pageerror', e => errs.push(String(e).slice(0,200))); p.on('console', m => m.type()==='error' && errs.push(m.text().slice(0,200)));
await p.goto('http://localhost:5175/'); await p.getByRole('button', { name: /Play EmotiTone/ }).waitFor({ timeout: 120000 }).catch(async () => { await p.screenshot({ path: 'x-fail.png' }); console.log('gate missing', errs); });
await p.getByRole('button', { name: /Play EmotiTone/ }).click(); await p.waitForTimeout(3000);
const state = () => p.evaluate(() => { const s = document.querySelector('#app').__vue_app__.config.globalProperties.$pinia._s; const l = s.get('loopPrototype'); const ph = s.get('phrases'); return { layers: l.layers.map(x => ({ bars: Math.round(x.lengthMs / 2000 * 100) / 100, starts: x.notes.map(n => Math.round(n.pressTime)) })), bars: l.bars, deskPlaying: l.isDeskPlaying, latched: l.latched, take: ph.takeNotes.length, recent: ph.shelves.recent.length, kept: ph.shelves.kept.length }; });
const play = async (keys, gap = 450) => { for (const k of keys) { await p.keyboard.down(k); await p.waitForTimeout(200); await p.keyboard.up(k); await p.waitForTimeout(gap - 200); } };
const playBtn = () => p.locator('.code-strip-bar__play');
await play(['KeyA','KeyS','KeyD','KeyF','KeyA','KeyS','KeyD','KeyF']);
await playBtn().click(); await p.waitForTimeout(300);
console.log('1 play', JSON.stringify(await state()));
await play(['KeyG','KeyH']);
console.log('2 overlay', JSON.stringify(await state()));
await playBtn().click(); await p.waitForTimeout(300);
console.log('3 join', JSON.stringify(await state()));
await playBtn().click(); await p.waitForTimeout(300);
console.log('4 leave', JSON.stringify(await state()));
const box = await playBtn().boundingBox(); await p.mouse.move(box.x+box.width/2, box.y+box.height/2); await p.mouse.down(); await p.waitForTimeout(650); await p.mouse.up(); await p.waitForTimeout(300);
console.log('5 latch', JSON.stringify(await state()));
await play(['KeyJ','KeyK']); await p.waitForTimeout(2600);
console.log('6 auto-join', JSON.stringify(await state()));
await p.screenshot({ path: 'j-play.png' });
await p.getByRole('button', { name: 'Return' }).click(); await p.waitForTimeout(300);
await p.getByRole('button', { name: 'Stop all loops' }).click(); await p.waitForTimeout(300);
console.log('7 stop all', JSON.stringify(await state()));
console.log(errs.slice(0,6));
await b.close();
