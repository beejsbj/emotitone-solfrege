#!/usr/bin/env node
// Run from this checkout: node scripts/generate-visual-default-history.mjs [ref]
// Reads every ancestor revision of the metadata, including merged histories.
// Uses the TypeScript parser without executing historical application code.
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const root = fileURLToPath(new URL('../', import.meta.url));
const path = 'src/data/visual-config-metadata.ts';
const git = (...args) => execFileSync('git', args, { cwd: root, encoding: 'utf8' }).trim();
if (git('rev-parse', '--is-shallow-repository') === 'true') throw new Error('Full Git history is required');
const ref = process.argv[2] ?? 'HEAD';
const revisions = git('log', '--full-history', '--format=%H', ref, '--', path).split('\n').sort();
const history = {};
function property(object, name) {
  return object.properties.find(p => ts.isPropertyAssignment(p) && p.name.getText().replace(/["']/g, '') === name)?.initializer;
}
function literal(node) {
  if (ts.isAsExpression(node) || ts.isParenthesizedExpression(node)) return literal(node.expression);
  if (ts.isNumericLiteral(node)) return Number(node.text);
  if (ts.isStringLiteral(node)) return node.text;
  if (node.kind === ts.SyntaxKind.TrueKeyword) return true;
  if (node.kind === ts.SyntaxKind.FalseKeyword) return false;
  if (ts.isPrefixUnaryExpression(node) && node.operator === ts.SyntaxKind.MinusToken) return -literal(node.operand);
  throw new Error(`Unsupported default: ${node.getText()}`);
}
for (const revision of revisions) {
  const source = ts.createSourceFile(path, git('show', `${revision}:${path}`), ts.ScriptTarget.Latest, true);
  let config;
  const visit = (node) => {
    if (ts.isVariableDeclaration(node) && node.name.getText() === 'UNIFIED_CONFIG') config = node.initializer;
    ts.forEachChild(node, visit);
  };
  visit(source);
  if (!config || !ts.isObjectLiteralExpression(config)) throw new Error(`Missing UNIFIED_CONFIG at ${revision}`);
  for (const section of config.properties) {
    if (!ts.isPropertyAssignment(section) || !ts.isObjectLiteralExpression(section.initializer)) continue;
    const sectionName = section.name.getText().replace(/["']/g, '');
    for (const field of section.initializer.properties) {
      if (!ts.isPropertyAssignment(field) || !ts.isObjectLiteralExpression(field.initializer)) continue;
      const value = property(field.initializer, 'value');
      if (!value) continue;
      const fieldName = field.name.getText().replace(/["']/g, '');
      const defaults = (history[sectionName] ??= {})[fieldName] ??= [];
      const parsed = literal(value);
      if (!defaults.includes(parsed)) defaults.push(parsed);
    }
  }
}
const sorted = Object.fromEntries(Object.keys(history).sort().map(section => [section,
  Object.fromEntries(Object.keys(history[section]).sort().map(field => [field,
    history[section][field].sort((a, b) => JSON.stringify(a).localeCompare(JSON.stringify(b), 'en')),
  ])),
]));
const sections = Object.entries(sorted).map(([section, fields]) => {
  const rows = Object.entries(fields).map(([field, values]) => `    ${JSON.stringify(field)}: ${JSON.stringify(values)}`);
  return `  ${JSON.stringify(section)}: {\n${rows.join(',\n')}\n  }`;
});
const output = `// Generated by scripts/generate-visual-default-history.mjs. Do not edit.\n` +
  `// Full metadata history through ${git('rev-parse', `${ref}:${path}`)} (Git blob).\n` +
  `// Includes current defaults and retired fields for reconciliation before legacy conversions.\n` +
  `export const HISTORICAL_VISUAL_DEFAULTS: Record<string, Record<string, unknown[]>> = {\n${sections.join(',\n')}\n};\n`;
writeFileSync(new URL('../src/data/visual-config-default-history.ts', import.meta.url), output);
console.log(`Collected ${revisions.length} revisions into src/data/visual-config-default-history.ts`);
