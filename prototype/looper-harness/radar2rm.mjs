import { chromium } from 'playwright';
const OUT = '/tmp/looper-pw/radar2/rm/';
const b = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required'] });
const p = await b.newPage({ viewport: { width: 390, height: 844 }, hasTouch: true, deviceScaleFactor: 2, reducedMotion: process.env.RM ? 'reduce' : 'no-preference' });
const errs = []; p.on('pageerror', e => errs.push(String(e))); p.on('console', m => m.type()==='error' && errs.push(m.text()));
await p.goto('http://localhost:5183/');
await p.waitForTimeout(4000);
await p.getByRole('button', { name: /Play EmotiTone/ }).click({ timeout: 60000 });
await p.waitForTimeout(3000);
const L = (fn) => p.evaluate(`(() => { const l = document.querySelector('#app').__vue_app__.config.globalProperties.$pinia._s.get('loopPrototype'); return (${fn})(l); })()`);
const play = async (keys, gap = 380) => { for (const k of keys) { await p.keyboard.down(k); await p.waitForTimeout(180); await p.keyboard.up(k); await p.waitForTimeout(gap - 180); } };
const shotAt = async (name, target) => { for (let i = 0; i < 400; i++) { const ph = await L('l => l.phase()'); if (Math.abs(ph - target) < 0.02) break; await p.waitForTimeout(15); } await p.screenshot({ path: OUT + name + '.png', clip: { x: 0, y: 0, width: 390, height: 420 } }); };
await play(['KeyA','KeyD','KeyG','KeyJ','KeyG','KeyD']);
await p.getByRole('button', { name: 'Loop mode' }).click(); await p.waitForTimeout(300);
await p.getByRole('button', { name: 'Add to loop' }).click();
await p.waitForTimeout(300);
await p.screenshot({ path: OUT + 'a-fadein.png' });
console.log(await L('l => ({len: l.lengthMs, bars: l.bars, layers: l.layers.length, running: l.running})'));
for (const t of [0.1, 0.35, 0.6, 0.85]) await shotAt('b-one-' + t, t);
await play(['KeyS','KeyF','KeyH','KeyF'], 300);
await play(['KeyK','KeyJ','KeyH','KeyG'], 250);
await p.screenshot({ path: OUT + 'c-pending.png' });
await p.getByRole('button', { name: 'Add to loop' }).click(); await p.waitForTimeout(300);
await play(['KeyA','KeyA','KeyS','KeyA'], 500);
await p.getByRole('button', { name: 'Add to loop' }).click(); await p.waitForTimeout(300);
console.log(await L('l => l.layers.map(x => x.notes.length + "/" + x.lengthMs)'));
for (const t of [0.2, 0.55, 0.9]) await shotAt('d-three-' + t, t);
await L('l => { l.toggleMute(l.layers[1].id); return true; }');
await shotAt('e-muted-0.5', 0.5);
await L('l => { l.toggle(); return l.running; }');
await p.waitForTimeout(250); await p.screenshot({ path: OUT + 'f-stopping.png' });
await p.waitForTimeout(1500); await p.screenshot({ path: OUT + 'g-stopped.png' });
console.log(errs.slice(0, 8));
await b.close();
